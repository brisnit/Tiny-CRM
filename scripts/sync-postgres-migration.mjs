#!/usr/bin/env node
/**
 * Regenerates the PostgreSQL migration history from the schema.
 *
 * Prisma locks a migration history to the provider it was authored against
 * (`migration_lock.toml`), and the SQL inside is written in that engine's
 * dialect — so one history cannot serve both. Rather than hand-maintain two,
 * the PostgreSQL history is a single squashed `init` regenerated from the
 * schema, which is the source of truth for both engines.
 *
 * This is safe *before* the first PostgreSQL deployment. Once a real database
 * exists, a squash would try to recreate tables that are already there: from
 * that point forward, add incremental migrations with
 *
 *   DATABASE_URL=<postgres-url> npx prisma migrate dev --name <change>
 *
 * and stop running this script. The check below refuses to squash a history
 * that already has more than the init migration.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const DIR = resolve(ROOT, "prisma/migrations-postgres");
const INIT = resolve(DIR, "00000000000000_init");

if (existsSync(DIR)) {
  const migrations = readdirSync(DIR).filter((name) => /^\d/.test(name));
  if (migrations.length > 1) {
    console.error(
      `Refusing to squash: ${DIR} already has ${migrations.length} migrations.\n` +
        "Once a PostgreSQL database has been deployed, add incremental migrations\n" +
        "with `prisma migrate dev` instead of regenerating this history.",
    );
    process.exit(1);
  }
}

mkdirSync(INIT, { recursive: true });
writeFileSync(
  resolve(DIR, "migration_lock.toml"),
  '# Please do not edit this file manually\n' +
    '# It should be added in your version-control system (e.g., Git)\n' +
    'provider = "postgresql"\n',
);

// `--from-empty` produces the whole schema as PostgreSQL DDL without needing a
// server to compare against.
const sql = execFileSync(
  "npx",
  ["prisma", "migrate", "diff", "--from-empty", "--to-schema", "prisma/schema.prisma", "--script"],
  { cwd: ROOT, encoding: "utf8", env: { ...process.env, DATABASE_URL: "postgresql://x/x" } },
);

writeFileSync(resolve(INIT, "migration.sql"), sql);
console.log(`Wrote ${sql.split("\n").length} lines to prisma/migrations-postgres/00000000000000_init/migration.sql`);
console.log("Remember: the datasource provider in prisma/schema.prisma must be postgresql when this runs.");

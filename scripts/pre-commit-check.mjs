#!/usr/bin/env node
/**
 * The small set of mistakes that have actually reached main.
 *
 * Not a hook framework and not a second CI. CI remains authoritative; this
 * exists because three of the failures in this repository's history were the
 * same shape — a working tree carrying residue from a test harness, swept into
 * a commit by a broad `git add`. Every check here corresponds to something that
 * really happened, and each one names the fix in its message.
 *
 * Runs against the *staged* content, because that is what is about to become a
 * commit. Unstaged residue is not this script's business.
 *
 *   node scripts/pre-commit-check.mjs
 *   git config core.hooksPath .githooks     # to run it automatically
 */
import { execFileSync } from "node:child_process";

const problems = [];
const git = (args) => execFileSync("git", args, { encoding: "utf8" }).trim();

const staged = git(["diff", "--cached", "--name-only"]).split("\n").filter(Boolean);
if (staged.length === 0) process.exit(0);

// 1. The datasource provider. `npm run test:pg` flips it and an interrupted run
//    leaves it flipped; committing that turns five CI jobs red on a commit that
//    has nothing to do with the database. This has happened twice.
if (staged.includes("prisma/schema.prisma")) {
  const content = git(["show", ":prisma/schema.prisma"]);
  const provider = /datasource\s+db\s*\{[^}]*provider\s*=\s*"([^"]+)"/.exec(content)?.[1];
  if (provider !== "sqlite") {
    problems.push(
      `prisma/schema.prisma is staged with provider = "${provider}", not "sqlite".\n` +
      `      Fix: node scripts/use-provider.mjs sqlite && git add prisma/schema.prisma`,
    );
  }
}

// 2. Credentials. Every secret in this project lives in ~/.config/tinycrm at
//    mode 600, deliberately outside the working tree. Nothing of that shape
//    should ever be staged.
const CREDENTIALS = /(^|\/)(\.env(\.|$)(?!example)|.*\.pem$|.*\.key$|.*credentials.*\.json$|.*-secret$|.*\.url$)/i;
for (const file of staged) {
  if (CREDENTIALS.test(file) && !/\.env\.example$|env\.production\.example$/.test(file)) {
    problems.push(`${file} looks like a credential file. Secrets belong in ~/.config/tinycrm, never in the repository.`);
  }
}

// 3. Harness output. These are gitignored, so staging one means it was forced.
const RESIDUE = /^(\.backup-test|\.pgdata-run|\.mail|\.next|node_modules|coverage|test-results|playwright-report|\.audit-)/;
for (const file of staged) {
  if (RESIDUE.test(file)) problems.push(`${file} is test-harness output and should not be committed.`);
}

// 4. Generated Prisma client. Untracked by design; committing it makes every
//    provider switch produce an enormous meaningless diff.
for (const file of staged) {
  if (file.startsWith("src/generated/")) {
    problems.push(`${file} is generated by \`prisma generate\` and is deliberately untracked.`);
  }
}

// 5. The secret scan, when gitleaks is available. Optional by design: a missing
//    tool must not block a commit, and CI runs it regardless.
try {
  execFileSync("gitleaks", ["protect", "--staged", "--no-banner", "--redact"], { stdio: "pipe" });
} catch (error) {
  if (error?.code !== "ENOENT") {
    problems.push("gitleaks flagged staged content. Run `gitleaks protect --staged --verbose` to see what.");
  }
}

if (problems.length) {
  console.error("\nCommit refused:\n");
  for (const p of problems) console.error(`  ✖ ${p}`);
  console.error("\nCI would catch these later; catching them here costs less.\n");
  process.exit(1);
}

#!/usr/bin/env node
/**
 * The list of migrations the committed code expects, written into the bundle.
 *
 * This exists because of a real incident: a schema change shipped to production
 * while the migration was still unapplied, and the readiness endpoint reported
 * green through it because it only ran `SELECT 1` and a table-exists check.
 * Nothing compared what the code expected against what the database had.
 *
 * Reading the migrations directory at request time is not an option — a
 * serverless bundle traces imported modules, not arbitrary folders, and a
 * readiness probe should not touch the filesystem anyway. So the list is a
 * plain TypeScript module, generated from the directories and committed.
 *
 * Committing generated output has one failure mode: somebody adds a migration
 * and forgets to regenerate. `--check` is the answer to that, and it runs in
 * CI, the same shape as scripts/engine-suites.mjs.
 *
 *   node scripts/migration-manifest.mjs           # rewrite the manifest
 *   node scripts/migration-manifest.mjs --check   # fail if it is stale
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const OUT = resolve(ROOT, "src/lib/db/migration-manifest.ts");

/** Migration folder names, in the order Prisma applies them. */
function migrationsIn(dir) {
  try {
    return readdirSync(resolve(ROOT, dir), { withFileTypes: true })
      .filter((entry) => entry.isDirectory() && /^\d/.test(entry.name))
      .map((entry) => entry.name)
      .sort();
  } catch {
    return [];
  }
}

function render() {
  const sqlite = migrationsIn("prisma/migrations");
  const postgres = migrationsIn("prisma/migrations-postgres");
  const list = (names) => names.map((n) => `  "${n}",`).join("\n");

  return `// GENERATED by scripts/migration-manifest.mjs — do not edit by hand.
//
// The migrations this build of the application expects the database to have
// applied. /api/ready compares this against \`_prisma_migrations\` so a deploy
// that is ahead of its schema reports not-ready instead of serving pages that
// throw. Regenerate with \`node scripts/migration-manifest.mjs\`; CI fails if
// this file and the migration directories disagree.

/** prisma/migrations — SQLite, local development and the fast suite. */
export const SQLITE_MIGRATIONS = [
${list(sqlite)}
] as const;

/** prisma/migrations-postgres — PostgreSQL, every deployed environment. */
export const POSTGRES_MIGRATIONS = [
${list(postgres)}
] as const;
`;
}

const generated = render();

if (process.argv[2] === "--check") {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    console.error(`${OUT} is missing. Run: node scripts/migration-manifest.mjs`);
    process.exit(1);
  }
  if (current !== generated) {
    console.error(
      "The migration manifest is stale — a migration was added or removed without regenerating it.\n" +
        "Run: node scripts/migration-manifest.mjs",
    );
    process.exit(1);
  }
  const sqlite = migrationsIn("prisma/migrations").length;
  const postgres = migrationsIn("prisma/migrations-postgres").length;
  console.log(`Migration manifest is current: ${sqlite} SQLite, ${postgres} PostgreSQL.`);
} else {
  writeFileSync(OUT, generated);
  console.log(`Wrote ${OUT}`);
}
